import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Writes the "Make it yours" and "Extend hos" pages from the hos skill's recipes. --check exits 1 when they are stale.
const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const skill = resolve(site, '../../skills/hos');
const recipesDir = join(skill, 'recipes');
const PAGE_OF_KIND = { brain: 'make-it-yours', code: 'extend-hos' };

function frontmatter(text, file) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (kv && kv[2] !== '') data[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1');
  }
  return { data, body: text.slice(m[0].length) };
}

function tableOrder() {
  const text = readFileSync(join(skill, 'SKILL.md'), 'utf8');
  return [...text.matchAll(/^\|[^|\n]*\|\s*`([a-z0-9-]+)`\s*\|\s*(brain|code)\s*\|$/gm)].map((m) => m[1]);
}

function outsideFences(text, fn) {
  let fenced = false;
  return text
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) fenced = !fenced;
      return fenced || /^\s*```/.test(line) ? line : fn(line);
    })
    .join('\n');
}

function escapeHtml(line) {
  return line
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;')))
    .join('');
}

function splitRecipe(body, file) {
  const at = body.search(/^## For the agent\s*$/m);
  if (at < 0) throw new Error(`${file}: no "## For the agent" section`);
  const people = body
    .slice(0, at)
    .replace(/^\s*# .*\n+/, '')
    .replace(/\n---\s*\n*$/, '')
    .trim();
  const agent = body.slice(at).replace(/^## For the agent\s*\n+/, '').trim();
  return {
    people: outsideFences(people, (l) => escapeHtml(l.replace(/^(#{2,3}) /, (_, h) => `${h}# `))),
    agent: outsideFences(agent, (l) => escapeHtml(l.replace(/^#{3,4} (.+)$/, '**$1**'))),
  };
}

export function loadRecipes() {
  const order = tableOrder();
  const files = readdirSync(recipesDir).filter((f) => f.endsWith('.md'));
  const recipes = files.map((f) => {
    const { data, body } = frontmatter(readFileSync(join(recipesDir, f), 'utf8'), f);
    const page = PAGE_OF_KIND[data.kind];
    if (!page) throw new Error(`${f}: kind must be brain or code`);
    if (`${data.id}.md` !== f) throw new Error(`${f}: id ${data.id} does not match the file name`);
    if (data.docs !== `${page}#${data.id}`) throw new Error(`${f}: docs must be ${page}#${data.id}, is ${data.docs}`);
    return { ...data, page, file: f, ...splitRecipe(body, f) };
  });
  const rank = (id) => (order.includes(id) ? order.indexOf(id) : order.length);
  return recipes.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
}

const slug = (title) => title.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');

function section(r) {
  return [
    ...(slug(r.title) === r.id ? [] : [`<a id="${r.id}"></a>`, '']),
    `## ${r.title}`,
    '',
    r.people,
    '',
    '<details>',
    '<summary>What the agent does</summary>',
    '',
    `The full recipe is \`skills/hos/recipes/${r.file}\` in your brain (size ${r.size ?? '?'}, for hos \`${r.hos ?? '?'}\`).`,
    '',
    r.agent,
    '',
    '</details>',
    '',
  ].join('\n');
}

export function renderPage(slug, recipes) {
  const template = readFileSync(join(site, 'recipe-pages', `${slug}.md`), 'utf8');
  if (!template.includes('<!-- recipes -->')) throw new Error(`recipe-pages/${slug}.md: no <!-- recipes --> line`);
  const body = recipes.filter((r) => r.page === slug).map(section).join('\n');
  const head = '<!-- Generated by scripts/gen-recipes.mjs from skills/hos/recipes/. Edit the recipes or recipe-pages/, not this file. -->';
  return template.replace(/^(---\n[\s\S]*?\n---\n)/, `$1\n${head}\n`).replace('<!-- recipes -->', body.trimEnd());
}

const check = process.argv.includes('--check');
const recipes = loadRecipes();
let stale = 0;
for (const slug of Object.values(PAGE_OF_KIND)) {
  const target = join(site, 'src/content/docs/docs', `${slug}.md`);
  const next = `${renderPage(slug, recipes).trimEnd()}\n`;
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current === next) continue;
  if (check) {
    console.error(`stale: ${target} (run: node docs/site/scripts/gen-recipes.mjs)`);
    stale++;
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${target}`);
  }
}
process.exit(stale ? 1 : 0);
